# ---------------------------------------------------------------------------------------------
# Unattended setup: copy, generate and validate Autounattend.xml
# ---------------------------------------------------------------------------------------------

$script:TkUnattendNs = 'urn:schemas-microsoft-com:unattend'
$script:TkUnattendPasses = @('windowsPE', 'offlineServicing', 'generalize', 'specialize', 'auditSystem', 'auditUser', 'oobeSystem')

function Copy-TkPersonalUnattend {
    <# Copies Custom\Autounattend.xml to the root of the DVD folder. #>
    [CmdletBinding()]
    param([string]$Path = (Join-Path $script:TK.Paths.Custom 'Autounattend.xml'))
    if (-not (Test-Path -LiteralPath $Path)) { throw "Personal answer file '$Path' not found." }
    $issues = @(Test-TkUnattendXml -Path $Path)
    foreach ($issue in $issues) { Write-TkLog $issue -Level Warn }
    Copy-Item -LiteralPath $Path -Destination (Join-Path $script:TK.Paths.DVD 'Autounattend.xml') -Force
    Write-TkLog 'Autounattend.xml copied to the DVD folder.' -Level Success
}

function Get-TkHostRegionalSetting {
    <# Regional settings of this PC in unattend format. #>
    [CmdletBinding()]
    [OutputType([hashtable])]
    param()
    $languages = @(Get-WinUserLanguageList)
    $inputLocale = if ($languages.Count -gt 0 -and @($languages[0].InputMethodTips).Count -gt 0) { @($languages[0].InputMethodTips)[0] } else { '0409:00000409' }
    @{
        UILanguage   = [System.Globalization.CultureInfo]::InstalledUICulture.Name
        SystemLocale = (Get-WinSystemLocale).Name
        UserLocale   = (Get-Culture).Name
        InputLocale  = $inputLocale
        TimeZone     = (Get-TimeZone).Id
    }
}

function Get-TkImageRegionalSetting {
    <# Regional settings of the first mounted install image (dism /Get-Intl). #>
    [CmdletBinding()]
    [OutputType([hashtable])]
    param()
    Assert-TkSource -AllowRegistryLoaded
    $image = @(Get-TkImage -Kind Install)[0]
    $output = Invoke-TkDismExe -ArgumentList @("/Image:$($image.Path)", '/Get-Intl') -Quiet
    $intl = ConvertFrom-TkDismIntlOutput -Line @($output)
    if (-not $intl.UserLocale) { $intl.UserLocale = $intl.SystemLocale }
    $intl
}

function ConvertTo-TkUnattendPassword {
    <# Encodes a password the way Windows SIM does (Base64 of UTF-16LE password + suffix). #>
    [CmdletBinding()]
    [OutputType([string])]
    param(
        [Parameter(Mandatory)][securestring]$Password,
        [string]$Suffix = 'Password'
    )
    $plain = [System.Net.NetworkCredential]::new('', $Password).Password
    [Convert]::ToBase64String([System.Text.Encoding]::Unicode.GetBytes($plain + $Suffix))
}

function New-TkUnattendXml {
    <#
    .SYNOPSIS
        Generates an Autounattend.xml for Windows 11 setup (returns the XML text).
    .DESCRIPTION
        The disk configuration is intentionally NOT automated: Windows Setup still asks where to
        install, so the file cannot wipe a disk by accident.
    .PARAMETER BypassHardwareCheck
        Adds LabConfig registry values in the windowsPE pass (TPM/Secure Boot/CPU/RAM/storage).
    .PARAMETER BypassNetworkRequirement
        Sets BypassNRO during specialize (allows OOBE without network).
    #>
    [CmdletBinding()]
    [OutputType([string])]
    param(
        [ValidateSet('amd64', 'arm64')][string]$Architecture = 'amd64',
        [string]$UILanguage = 'en-US',
        [string]$SystemLocale = 'en-US',
        [string]$UserLocale = 'en-US',
        [string]$InputLocale = '0409:00000409',
        [string]$UILanguageFallback,
        [string]$TimeZone = 'UTC',
        [string]$ComputerName,
        [string]$Organization,
        [string]$Owner,
        [string]$ProductKey,
        [string]$AccountName,
        [securestring]$AccountPassword,
        [switch]$AutoLogon,
        [ValidateRange(1, 999)][int]$AutoLogonCount = 1,
        [switch]$BypassHardwareCheck,
        [switch]$BypassNetworkRequirement,
        [switch]$PreventDeviceEncryption,
        [switch]$HideWirelessSetup
    )

    $x = { param([string]$s) [System.Security.SecurityElement]::Escape($s) }
    $attributes = "processorArchitecture=`"$Architecture`" publicKeyToken=`"31bf3856ad364e35`" language=`"neutral`" versionScope=`"nonSxS`" xmlns:wcm=`"http://schemas.microsoft.com/WMIConfig/2002/State`" xmlns:xsi=`"http://www.w3.org/2001/XMLSchema-instance`""
    $component = { param([string]$name, [string]$body) "        <component name=`"$name`" $attributes>`r`n$body`r`n        </component>" }
    $sb = [System.Text.StringBuilder]::new()
    $line = { param([string]$text) $null = $sb.AppendLine($text) }

    & $line '<?xml version="1.0" encoding="utf-8"?>'
    & $line '<!-- Generated by MSMG Toolkit PS7 -->'
    & $line "<unattend xmlns=`"$($script:TkUnattendNs)`">"

    # ------------------------------------------------------------------ windowsPE
    & $line '    <settings pass="windowsPE">'
    $intlPe = @(
        "            <SetupUILanguage>`r`n                <UILanguage>$(& $x $UILanguage)</UILanguage>`r`n            </SetupUILanguage>"
        "            <InputLocale>$(& $x $InputLocale)</InputLocale>"
        "            <SystemLocale>$(& $x $SystemLocale)</SystemLocale>"
        "            <UILanguage>$(& $x $UILanguage)</UILanguage>"
    )
    if ($UILanguageFallback) { $intlPe += "            <UILanguageFallback>$(& $x $UILanguageFallback)</UILanguageFallback>" }
    $intlPe += "            <UserLocale>$(& $x $UserLocale)</UserLocale>"
    & $line (& $component 'Microsoft-Windows-International-Core-WinPE' ($intlPe -join "`r`n"))

    $setup = [System.Collections.Generic.List[string]]::new()
    if ($BypassHardwareCheck) {
        $setup.Add('            <RunSynchronous>')
        $order = 1
        foreach ($check in 'BypassTPMCheck', 'BypassSecureBootCheck', 'BypassCPUCheck', 'BypassRAMCheck', 'BypassStorageCheck') {
            $setup.Add('                <RunSynchronousCommand wcm:action="add">')
            $setup.Add("                    <Order>$order</Order>")
            $setup.Add("                    <Path>reg.exe add HKLM\SYSTEM\Setup\LabConfig /v $check /t REG_DWORD /d 1 /f</Path>")
            $setup.Add('                </RunSynchronousCommand>')
            $order++
        }
        $setup.Add('            </RunSynchronous>')
    }
    $setup.Add('            <Diagnostics>')
    $setup.Add('                <OptIn>false</OptIn>')
    $setup.Add('            </Diagnostics>')
    $setup.Add('            <DynamicUpdate>')
    $setup.Add('                <Enable>false</Enable>')
    $setup.Add('                <WillShowUI>OnError</WillShowUI>')
    $setup.Add('            </DynamicUpdate>')
    $setup.Add('            <UserData>')
    $setup.Add('                <AcceptEula>true</AcceptEula>')
    if ($Owner) { $setup.Add("                <FullName>$(& $x $Owner)</FullName>") }
    if ($Organization) { $setup.Add("                <Organization>$(& $x $Organization)</Organization>") }
    $setup.Add('                <ProductKey>')
    $setup.Add("                    <Key>$(& $x $ProductKey)</Key>")
    $setup.Add('                    <WillShowUI>OnError</WillShowUI>')
    $setup.Add('                </ProductKey>')
    $setup.Add('            </UserData>')
    & $line (& $component 'Microsoft-Windows-Setup' ($setup -join "`r`n"))
    & $line '    </settings>'

    # ------------------------------------------------------------------ offlineServicing
    if ($PreventDeviceEncryption) {
        & $line '    <settings pass="offlineServicing">'
        & $line (& $component 'Microsoft-Windows-SecureStartup-FilterDriver' '            <PreventDeviceEncryption>true</PreventDeviceEncryption>')
        & $line '    </settings>'
    }

    # ------------------------------------------------------------------ specialize
    & $line '    <settings pass="specialize">'
    $shell = [System.Collections.Generic.List[string]]::new()
    $shell.Add("            <ComputerName>$(if ($ComputerName) { & $x $ComputerName } else { '*' })</ComputerName>")
    if ($Organization) { $shell.Add("            <RegisteredOrganization>$(& $x $Organization)</RegisteredOrganization>") }
    if ($Owner) { $shell.Add("            <RegisteredOwner>$(& $x $Owner)</RegisteredOwner>") }
    $shell.Add("            <TimeZone>$(& $x $TimeZone)</TimeZone>")
    & $line (& $component 'Microsoft-Windows-Shell-Setup' ($shell -join "`r`n"))
    if ($BypassNetworkRequirement) {
        $deploy = @(
            '            <RunSynchronous>'
            '                <RunSynchronousCommand wcm:action="add">'
            '                    <Order>1</Order>'
            '                    <Path>reg.exe add HKLM\SOFTWARE\Microsoft\Windows\CurrentVersion\OOBE /v BypassNRO /t REG_DWORD /d 1 /f</Path>'
            '                </RunSynchronousCommand>'
            '            </RunSynchronous>'
        )
        & $line (& $component 'Microsoft-Windows-Deployment' ($deploy -join "`r`n"))
    }
    & $line '    </settings>'

    # ------------------------------------------------------------------ oobeSystem
    & $line '    <settings pass="oobeSystem">'
    $intl = @(
        "            <InputLocale>$(& $x $InputLocale)</InputLocale>"
        "            <SystemLocale>$(& $x $SystemLocale)</SystemLocale>"
        "            <UILanguage>$(& $x $UILanguage)</UILanguage>"
    )
    if ($UILanguageFallback) { $intl += "            <UILanguageFallback>$(& $x $UILanguageFallback)</UILanguageFallback>" }
    $intl += "            <UserLocale>$(& $x $UserLocale)</UserLocale>"
    & $line (& $component 'Microsoft-Windows-International-Core' ($intl -join "`r`n"))

    $oobe = [System.Collections.Generic.List[string]]::new()
    $oobe.Add('            <OOBE>')
    $oobe.Add('                <HideEULAPage>true</HideEULAPage>')
    $oobe.Add('                <HideOEMRegistrationScreen>true</HideOEMRegistrationScreen>')
    if ($AccountName) {
        $oobe.Add('                <HideLocalAccountScreen>true</HideLocalAccountScreen>')
        $oobe.Add('                <HideOnlineAccountScreens>true</HideOnlineAccountScreens>')
    }
    if ($HideWirelessSetup) { $oobe.Add('                <HideWirelessSetupInOOBE>true</HideWirelessSetupInOOBE>') }
    $oobe.Add('                <ProtectYourPC>3</ProtectYourPC>')
    $oobe.Add('            </OOBE>')
    $oobe.Add("            <TimeZone>$(& $x $TimeZone)</TimeZone>")
    if ($Organization) { $oobe.Add("            <RegisteredOrganization>$(& $x $Organization)</RegisteredOrganization>") }
    if ($Owner) { $oobe.Add("            <RegisteredOwner>$(& $x $Owner)</RegisteredOwner>") }
    if ($AccountName) {
        $passwordXml = if ($AccountPassword -and $AccountPassword.Length -gt 0) {
            "                        <Password>`r`n                            <Value>$(ConvertTo-TkUnattendPassword -Password $AccountPassword)</Value>`r`n                            <PlainText>false</PlainText>`r`n                        </Password>"
        }
        else {
            "                        <Password>`r`n                            <Value></Value>`r`n                            <PlainText>true</PlainText>`r`n                        </Password>"
        }
        $oobe.Add('            <UserAccounts>')
        $oobe.Add('                <LocalAccounts>')
        $oobe.Add('                    <LocalAccount wcm:action="add">')
        $oobe.Add("                        <Name>$(& $x $AccountName)</Name>")
        $oobe.Add("                        <DisplayName>$(& $x $AccountName)</DisplayName>")
        $oobe.Add('                        <Group>Administrators</Group>')
        $oobe.Add($passwordXml)
        $oobe.Add('                    </LocalAccount>')
        $oobe.Add('                </LocalAccounts>')
        $oobe.Add('            </UserAccounts>')
        if ($AutoLogon) {
            $oobe.Add('            <AutoLogon>')
            $oobe.Add('                <Enabled>true</Enabled>')
            $oobe.Add("                <LogonCount>$AutoLogonCount</LogonCount>")
            $oobe.Add("                <Username>$(& $x $AccountName)</Username>")
            $oobe.Add(($passwordXml -replace '(?m)^ {8}', ''))
            $oobe.Add('            </AutoLogon>')
        }
    }
    & $line (& $component 'Microsoft-Windows-Shell-Setup' ($oobe -join "`r`n"))
    & $line '    </settings>'
    & $line '</unattend>'
    $sb.ToString()
}

function Write-TkUnattendXml {
    <#
    .SYNOPSIS
        Generates Autounattend.xml into the DVD folder (all parameters of New-TkUnattendXml are accepted).
    .PARAMETER RegionalSource
        Host  = take language/keyboard/time zone of this PC
        Image = take them from the mounted install image
    #>
    [CmdletBinding()]
    param(
        [ValidateSet('Host', 'Image')][string]$RegionalSource = 'Host',
        [hashtable]$Option = @{},
        [string]$Path = (Join-Path $script:TK.Paths.DVD 'Autounattend.xml')
    )
    $regional = if ($RegionalSource -eq 'Image') { Get-TkImageRegionalSetting } else { Get-TkHostRegionalSetting }
    $params = @{}
    foreach ($key in 'UILanguage', 'SystemLocale', 'UserLocale', 'InputLocale', 'TimeZone') {
        if ($regional[$key]) { $params[$key] = $regional[$key] }
    }
    if ($script:TK.Session.SourceSelected) {
        $params.Architecture = Get-TkUnattendArchitecture -Architecture $script:TK.Session.ImageInfo.Architecture
    }
    foreach ($key in @($Option.Keys)) { $params[$key] = $Option[$key] }

    $xml = New-TkUnattendXml @params
    $Path = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($Path)
    [System.IO.File]::WriteAllText($Path, $xml, [System.Text.UTF8Encoding]::new($false))
    $issues = @(Test-TkUnattendXml -Path $Path)
    foreach ($issue in $issues) { Write-TkLog $issue -Level Warn }
    Write-TkLog "Answer file written to '$Path'." -Level Success
}

function Test-TkUnattendXml {
    <#
    .SYNOPSIS
        Performs a structural check of an answer file. Returns a list of problems (empty = OK).
    #>
    [CmdletBinding()]
    [OutputType([string[]])]
    param(
        [Parameter(Mandatory)][string]$Path,
        [string]$Architecture
    )
    $issues = [System.Collections.Generic.List[string]]::new()
    if (-not (Test-Path -LiteralPath $Path)) { return "File not found: $Path" }
    try {
        $doc = [xml](Get-Content -LiteralPath $Path -Raw)
    }
    catch {
        return "Invalid XML: $($_.Exception.Message)"
    }
    if (-not $Architecture -and $script:TK -and $script:TK.Session.SourceSelected) {
        $Architecture = Get-TkUnattendArchitecture -Architecture $script:TK.Session.ImageInfo.Architecture
    }
    $root = $doc.DocumentElement
    if ($root.LocalName -ne 'unattend' -or $root.NamespaceURI -ne $script:TkUnattendNs) {
        $issues.Add("Root element must be <unattend xmlns=`"$($script:TkUnattendNs)`">.")
        return $issues.ToArray()
    }
    $ns = [System.Xml.XmlNamespaceManager]::new($doc.NameTable)
    $ns.AddNamespace('u', $script:TkUnattendNs)
    foreach ($settings in @($doc.SelectNodes('/u:unattend/u:settings', $ns))) {
        $pass = $settings.GetAttribute('pass')
        if ($script:TkUnattendPasses -notcontains $pass) { $issues.Add("Unknown configuration pass '$pass'.") }
        foreach ($comp in @($settings.SelectNodes('u:component', $ns))) {
            $name = $comp.GetAttribute('name')
            foreach ($attr in 'name', 'processorArchitecture', 'publicKeyToken', 'language', 'versionScope') {
                if (-not $comp.GetAttribute($attr)) { $issues.Add("Component '$name' in pass '$pass' has no '$attr' attribute.") }
            }
            $arch = $comp.GetAttribute('processorArchitecture')
            if ($Architecture -and $arch -and $arch -ne $Architecture) {
                $issues.Add("Component '$name' in pass '$pass' targets '$arch' but the image is '$Architecture' (it will be ignored).")
            }
        }
    }
    if (@($doc.SelectNodes('//u:DiskConfiguration', $ns)).Count -gt 0) {
        $issues.Add('Note: the answer file contains a DiskConfiguration - setup may wipe disks without asking.')
    }
    $issues.ToArray()
}
